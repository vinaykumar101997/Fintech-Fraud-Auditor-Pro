"""Measure Tiers 0 and 1 on the IBM AML transaction files from Kaggle.

    python scripts/eval_external.py --path data/external/HI-Small_Trans.csv --max-rows 50000

The files (HI-Small_Trans.csv, LI-Medium_Trans.csv, ...) are synthetic
transactions generated by IBM's AMLworld simulator, labelled per row. They have
no party names and no countries, so sanctions screening and the country rule
cannot fire; only the amount rules (Tier 1) and the behaviour model (Tier 0)
are measured. Laundering is rare (about 0.1% of rows in the HI files), so the
script prints PR-AUC and precision@k next to recall and precision.

Column mapping (the header is checked before anything is read):

    IBM column                      ledger column
    line number in the file         transaction_id  ("L2" is the first data row)
    Timestamp (YYYY/MM/DD HH:MM)    timestamp
    From Bank + "-" + Account       sender
    To Bank + "-" + Account         receiver   (second "Account" column)
    Amount Paid                     amount     (in Payment Currency)
    Payment Currency                used only by --currency
    Is Laundering                   label, kept away from the pipeline
    (none)                          country    (left blank)
    Amount Received, Receiving Currency, Payment Format: not used

Bank codes are kept exactly as written, so "0213" and "00213" are different
banks. A row whose sender and receiver are the same account is a self-transfer
(most are "Reinvestment"): the pipeline leaves it out of the amount rules and
the behaviour model, it is counted separately, and it ranks last for PR-AUC
and precision@k unless another rule flags it. No currency conversion is done: by default only rows paid in US Dollar
are kept, because the amount rules and features compare raw amounts. Rows are
taken from the top of the file until --max-rows rows are kept; the file is not
in time order, so that sample is not a clean time window. --start and --end
select rows by their parsed timestamp instead (both days inclusive), sorted by
time, with --max-rows keeping the earliest.
"""

from __future__ import annotations

import argparse
import csv
import io
import sys
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Tuple

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import config  # noqa: E402
from evaluate import metrics, wilson_interval  # noqa: E402
from utils.data_loader import load_ledger  # noqa: E402
from utils.funnel import run_funnel  # noqa: E402
from utils.rules import apply_rules  # noqa: E402

IBM_HEADER = [
    "Timestamp", "From Bank", "Account", "To Bank", "Account", "Amount Received",
    "Receiving Currency", "Amount Paid", "Payment Currency", "Payment Format", "Is Laundering",
]
_COLUMNS = [
    "timestamp", "from_bank", "from_account", "to_bank", "to_account", "amount_received",
    "receiving_currency", "amount_paid", "payment_currency", "payment_format", "is_laundering",
]
LEDGER_COLUMNS = ["transaction_id", "timestamp", "sender", "receiver", "amount", "country"]

# IsolationForest.decision_function lies in [-0.5, 0.5] with contamination="auto",
# so adding this to rule-flagged rows ranks every one of them above the rest.
RULE_RANK_OFFSET = 10.0
_TIME_FORMAT = "%Y/%m/%d %H:%M"
MIN_POSITIVES = 30
DEFAULT_KS = [100, 500, 1000]

# Text unique to each reason utils.rules.evaluate_row writes. Matched as a
# substring; "reporting threshold" alone would also match the structuring band.
RULE_REASONS = {
    "reporting_threshold": "is at or above the",
    "structuring_band": "sits in the structuring band",
    "high_risk_country": "is on the high-risk list",
    "secrecy_jurisdiction": "is a recognised secrecy jurisdiction",
    "sanctions_name": "matches sanctions list entry",
    "unidentified_parties": "Both counterparties are unidentified",
    "unresolved_jurisdiction": "Unresolved jurisdiction",
    "self_transfer": "Self-transfer: sender and receiver are the same account",
}
# Low-severity notes: reported with the reasons but never forward a row.
NOTES = {"unresolved_jurisdiction", "self_transfer"}


def rule_id(reason: str) -> str:
    for rid, text in RULE_REASONS.items():
        if text in reason:
            return rid
    return "other"


def _breakdown_row(source: str, fired: pd.Series, truth: pd.Series, investigate: pd.Series,
                   forwarded: int, note: bool = False) -> dict:
    rows = int(fired.sum())
    laundering = int((fired & (truth == 1)).sum())
    return {
        "source": source,
        "rows": rows,
        "laundering": laundering,
        "precision": laundering / rows if rows else None,
        "share_of_forwarded": int((fired & investigate).sum()) / forwarded if forwarded else 0.0,
        "note": note,
    }


def source_breakdown(scored: pd.DataFrame, truth: pd.Series) -> List[dict]:
    """Rows fired, laundering rows fired, precision and share of forwarded rows,
    for each rule (most rows first), any rule, and the behaviour model."""
    investigate = scored["investigate"].astype(bool)
    forwarded = int(investigate.sum())
    ids = scored["rule_reasons"].map(lambda reasons: {rule_id(r) for r in reasons or []})
    rules = [_breakdown_row(rid, ids.map(lambda s, rid=rid: rid in s), truth, investigate,
                            forwarded, note=rid in NOTES)
             for rid in RULE_REASONS]
    other = ids.map(lambda s: "other" in s)
    if other.any():
        rules.append(_breakdown_row("other", other, truth, investigate, forwarded))
    rules.sort(key=lambda b: -b["rows"])

    rule_flag = scored["rule_flag"].astype(bool)
    model = scored["ml_anomaly"].astype(bool)
    return rules + [
        _breakdown_row("any rule", rule_flag, truth, investigate, forwarded),
        _breakdown_row("behaviour model", model, truth, investigate, forwarded),
        _breakdown_row("behaviour model only", model & ~rule_flag, truth, investigate, forwarded),
    ]


def _norm(cell: str) -> str:
    return " ".join(cell.split()).lower()


def read_header(path: Path) -> List[str]:
    with open(path, newline="", encoding="utf-8-sig") as fh:
        return [cell.strip() for cell in next(csv.reader(fh), [])]


def _parse_day(value) -> Optional[pd.Timestamp]:
    return None if value is None else pd.Timestamp(value).normalize()


def read_ibm(path: Path, max_rows: int, currency: str = "US Dollar",
             chunksize: int = 200_000, start=None, end=None) -> Tuple[pd.DataFrame, dict]:
    """Read up to max_rows rows (after the currency filter) in the ledger's columns.

    Without start/end, rows are taken from the top of the file. With either,
    the whole file is read, rows are kept whose parsed timestamp falls between
    start and end (both days inclusive), and they are sorted by time, so that
    a cap keeps the earliest rows by timestamp rather than by file position.

    Returns the frame, with `currency` and `is_laundering` beside the ledger
    columns, and {"rows_read", "currency_counts", "header"}, plus
    "rows_in_range" and "dates" for a date range. Raises ValueError if the
    header is not the IBM layout or no row matches.
    """
    header = read_header(path)
    if [_norm(c) for c in header] != [_norm(c) for c in IBM_HEADER]:
        raise ValueError(
            "Not the IBM AML transaction layout. Expected: " + ",".join(IBM_HEADER)
            + ". Found: " + ",".join(header)
        )
    reader = pd.read_csv(path, header=None, skiprows=1, names=_COLUMNS, dtype=str,
                         keep_default_na=False, chunksize=chunksize, encoding="utf-8-sig")
    keep_all = currency.strip().lower() == "all"
    if start is None and end is None:
        raw, info = _read_from_top(reader, max_rows, currency, keep_all)
    else:
        raw, info = _read_date_range(reader, max_rows, currency, keep_all,
                                     _parse_day(start), _parse_day(end))
    info["header"] = header

    if raw.empty:
        found = ", ".join(sorted(info["currency_counts"])) or "none"
        raise ValueError(
            f"No rows paid in {currency!r} among the {info['rows_read']:,} rows read"
            + (" in the date range" if "dates" in info else "")
            + f". Currencies found: {found}. Pass --currency with one of them, or all."
        )

    ts = pd.to_datetime(raw["timestamp"], format=_TIME_FORMAT, errors="coerce")
    frame = pd.DataFrame({
        "transaction_id": ["L" + str(i) for i in raw.index],
        "timestamp": ts.dt.strftime("%Y-%m-%d %H:%M:%S").fillna("").to_numpy(),
        "sender": (raw["from_bank"] + "-" + raw["from_account"]).to_numpy(),
        "receiver": (raw["to_bank"] + "-" + raw["to_account"]).to_numpy(),
        "amount": raw["amount_paid"].to_numpy(),
        "country": "",
        "currency": raw["payment_currency"].to_numpy(),
        "is_laundering": pd.to_numeric(raw["is_laundering"], errors="coerce").fillna(0)
        .astype(int).to_numpy(),
    })
    return frame, info


def _chunks(reader):
    for chunk in reader:
        chunk = chunk.apply(lambda col: col.str.strip())
        chunk.index = chunk.index + 2  # line number in the file
        yield chunk


def _add_counts(counts: Dict[str, int], values: pd.Series) -> None:
    for name, n in values.value_counts().items():
        counts[name] = counts.get(name, 0) + int(n)


def _read_from_top(reader, max_rows: int, currency: str, keep_all: bool):
    parts, kept, rows_read = [], 0, 0
    counts: Dict[str, int] = {}
    for chunk in _chunks(reader):
        if not keep_all:
            mask = chunk["payment_currency"] == currency
            if kept + int(mask.sum()) >= max_rows:
                # Stop at the row that completes max_rows; count only rows read.
                last = chunk.index[mask][max_rows - kept - 1]
                chunk = chunk.loc[:last]
            chunk_kept = chunk[chunk["payment_currency"] == currency]
        else:
            chunk = chunk.iloc[: max_rows - kept]
            chunk_kept = chunk
        rows_read += len(chunk)
        _add_counts(counts, chunk["payment_currency"])
        parts.append(chunk_kept)
        kept += len(chunk_kept)
        if kept >= max_rows:
            break
    raw = pd.concat(parts) if parts else pd.DataFrame(columns=_COLUMNS)
    return raw, {"rows_read": rows_read, "currency_counts": counts}


def _read_date_range(reader, max_rows: int, currency: str, keep_all: bool,
                     start: Optional[pd.Timestamp], end: Optional[pd.Timestamp]):
    if start is not None and end is not None and start > end:
        raise ValueError(f"The start date {start.date()} is after the end date {end.date()}.")
    stop = end + pd.Timedelta(days=1) if end is not None else None
    parts, rows_read = [], 0
    counts: Dict[str, int] = {}
    first = last = None
    for chunk in _chunks(reader):
        rows_read += len(chunk)
        ts = pd.to_datetime(chunk["timestamp"], format=_TIME_FORMAT, errors="coerce")
        if ts.notna().any():
            first = min(filter(None, [first, ts.min()]))
            last = max(filter(None, [last, ts.max()]))
        in_range = ts.notna()
        if start is not None:
            in_range &= ts >= start
        if stop is not None:
            in_range &= ts < stop
        chunk = chunk[in_range].assign(_ts=ts[in_range])
        _add_counts(counts, chunk["payment_currency"])
        parts.append(chunk if keep_all else chunk[chunk["payment_currency"] == currency])

    raw = pd.concat(parts) if parts else pd.DataFrame(columns=_COLUMNS + ["_ts"])
    label = f"{start.date() if start is not None else 'start'} to {end.date() if end is not None else 'end'}"
    if not counts:
        span = f"{first:%Y-%m-%d} to {last:%Y-%m-%d}" if first is not None else "none parsed"
        raise ValueError(f"No rows dated {label}. The file's dates run from {span}.")
    # Time order, ties in file order, so a cap keeps the earliest rows by timestamp.
    raw = raw.assign(_line=raw.index).sort_values(["_ts", "_line"], kind="stable")
    in_range = len(raw)
    raw = raw.head(max_rows).drop(columns=["_ts", "_line"])
    return raw, {"rows_read": rows_read, "currency_counts": counts,
                 "rows_in_range": in_range, "dates": label}


def anomaly_rank(scored: pd.DataFrame) -> pd.Series:
    """Higher means more anomalous. Rows the model did not score (self-transfers)
    rank below every scored row."""
    score = -scored["ml_score"].astype(float)
    floor = score.min() - 1.0 if score.notna().any() else 0.0
    return score.fillna(floor)


def ranking_score(scored: pd.DataFrame) -> pd.Series:
    """Higher means more suspicious: rule-flagged rows first, then by anomaly score."""
    return anomaly_rank(scored) + RULE_RANK_OFFSET * scored["rule_flag"].astype(float)


def average_precision(truth: pd.Series, score: pd.Series) -> Optional[float]:
    """PR-AUC as average precision. None when there is no laundering row."""
    from sklearn.metrics import average_precision_score

    if int(truth.sum()) == 0:
        return None
    return float(average_precision_score(truth.to_numpy(), score.to_numpy()))


def precision_at_k(truth: pd.Series, score: pd.Series, k: int) -> Optional[float]:
    """Share of laundering rows in the k highest scores; ties keep file order."""
    if k <= 0 or k > len(score):
        return None
    order = np.argsort(-score.to_numpy(), kind="stable")
    return float(truth.to_numpy()[order[:k]].mean())


def evaluate_external(path: Path, max_rows: int, currency: str = "US Dollar",
                      ks: Iterable[int] = DEFAULT_KS, start=None, end=None) -> dict:
    frame, info = read_ibm(path, max_rows, currency, start=start, end=end)

    limit = config.MAX_LEDGER_ROWS
    config.MAX_LEDGER_ROWS = max(limit, len(frame))
    try:
        ledger, warnings = load_ledger(io.StringIO(frame[LEDGER_COLUMNS].to_csv(index=False)))
    finally:
        config.MAX_LEDGER_ROWS = limit

    # No screener: the accounts carry no names to screen.
    result = run_funnel(apply_rules(ledger))
    scored = (pd.concat([result.flagged, result.dropped])
              .set_index("transaction_id").loc[ledger["transaction_id"]].reset_index(drop=True))
    labels = frame.set_index("transaction_id")["is_laundering"]
    truth = labels.loc[ledger["transaction_id"]].reset_index(drop=True)
    predicted = scored["investigate"].astype(bool)
    counts = metrics(truth, predicted)

    if result.ml_applied:
        score = ranking_score(scored)
        pr_auc = average_precision(truth, score)
        pr_auc_tier0 = average_precision(truth, anomaly_rank(scored))
        at_k = {k: precision_at_k(truth, score, k) for k in ks}
    else:
        pr_auc = pr_auc_tier0 = None
        at_k = {k: None for k in ks}

    return {
        "header": info["header"],
        "rows_read": info["rows_read"],
        "currency_counts": info["currency_counts"],
        "currency": currency,
        "dates": info.get("dates"),
        "rows_in_range": info.get("rows_in_range"),
        "warnings": warnings,
        "rows": len(ledger),
        "laundering": int(truth.sum()),
        "base_rate": float(truth.mean()) if len(truth) else 0.0,
        "forwarded": result.forwarded,
        "rule_flagged": result.rule_flagged,
        "ml_flagged": result.ml_flagged,
        "ml_applied": result.ml_applied,
        "self_transfers": result.self_transfers,
        "self_transfer_laundering": int(truth[scored["self_transfer"].astype(bool)].sum()),
        **counts,
        "pr_auc": pr_auc,
        "pr_auc_tier0": pr_auc_tier0,
        "precision_at": at_k,
        "by_source": source_breakdown(scored, truth),
    }


def report(r: dict) -> None:
    print("\n" + "=" * 66)
    print("EXTERNAL EVALUATION: IBM AML transactions, Tiers 0 and 1")
    print("=" * 66)
    print("header: " + ",".join(r["header"]))
    shown = ", ".join(f"{name} {n:,}" for name, n in
                      sorted(r["currency_counts"].items(), key=lambda kv: -kv[1])[:6])
    if r["dates"]:
        print(f"dates {r['dates']} (parsed timestamps, both days inclusive): "
              f"{r['rows_in_range']:,} rows in range, earliest {r['rows']:,} kept")
    print(f"rows read {r['rows_read']:,}; kept {r['rows']:,} paid in {r['currency']} "
          f"(payment currencies {'in range' if r['dates'] else 'read'}: {shown})")
    for warning in r["warnings"]:
        print(f"  warning: {warning}")
    print(f"laundering {r['laundering']:,} of {r['rows']:,} ({r['base_rate']:.3%})")
    if r["laundering"] < MIN_POSITIVES:
        print(f"  note: fewer than {MIN_POSITIVES} laundering rows, so every figure below is "
              "very noisy; raise --max-rows.")

    tp, fp, fn, tn = r["tp"], r["fp"], r["fn"], r["tn"]
    r_lo, r_hi = wilson_interval(tp, tp + fn)
    p_lo, p_hi = wilson_interval(tp, tp + fp)
    print(f"\nforwarded {r['forwarded']:,} ({r['rule_flagged']:,} by a rule, "
          f"{r['ml_flagged']:,} by the behaviour model, overlaps counted once)")
    print(f"  self-transfers {r['self_transfers']:,} not scored "
          f"({r['self_transfer_laundering']:,} labelled laundering)")
    print(f"  TP {tp:,}  FP {fp:,}  FN {fn:,}  TN {tn:,}")
    print(f"  recall    {r['recall']:.1%}  ({tp}/{tp + fn}), 95% Wilson {r_lo:.1%} to {r_hi:.1%}")
    print(f"  precision {r['precision']:.1%}  ({tp}/{tp + fp}), 95% Wilson {p_lo:.1%} to {p_hi:.1%}")
    print(f"  F1        {r['f1']:.3f}")

    print("\nby rule and behaviour model (a row can fire several)")
    print(f"  {'source':<26}{'rows':>9}{'laund.':>8}{'precision':>11}{'of forwarded':>14}")
    for b in r["by_source"]:
        precision = f"{b['precision']:.3%}" if b["precision"] is not None else "-"
        share = "(note, does not forward)" if b["note"] else f"{b['share_of_forwarded']:.1%}"
        print(f"  {b['source']:<26}{b['rows']:>9,}{b['laundering']:>8,}{precision:>11}  {share:>12}")
    if not r["ml_applied"]:
        print("  (behaviour model: did not run; every row forwarded by default)")

    if not r["ml_applied"]:
        print(f"\nThe batch is below MIN_ROWS_FOR_ML ({config.MIN_ROWS_FOR_ML}), so Tier 0 did "
              "not run and there is no score to rank by: no PR-AUC or precision@k.")
        return
    print("\nranking: rule-flagged rows first, then by anomaly score")
    print(f"  PR-AUC (average precision), Tiers 0+1  {r['pr_auc']:.5f}" if r["pr_auc"] is not None
          else "  PR-AUC: no laundering rows")
    if r["pr_auc_tier0"] is not None:
        print(f"  PR-AUC, anomaly score alone          {r['pr_auc_tier0']:.5f}")
    print(f"  PR-AUC of a random ranking           {r['base_rate']:.5f}  (the laundering rate)")
    for k, value in r["precision_at"].items():
        if value is None:
            print(f"  precision@{k:<6} n/a (fewer than {k} rows)")
        else:
            print(f"  precision@{k:<6} {value:.1%}  ({round(value * k)}/{k})")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--path", type=Path, required=True,
                        help="an IBM AML *_Trans.csv file, e.g. data/external/HI-Small_Trans.csv")
    parser.add_argument("--max-rows", type=int, default=50_000,
                        help="rows to keep after the currency filter: from the top of the file, "
                             "or with --start/--end the earliest by timestamp")
    parser.add_argument("--start", metavar="YYYY-MM-DD",
                        help="keep rows dated on or after this day (reads the whole file)")
    parser.add_argument("--end", metavar="YYYY-MM-DD",
                        help="keep rows dated on or before this day (reads the whole file)")
    parser.add_argument("--currency", default="US Dollar",
                        help="keep rows with this Payment Currency (default: US Dollar), or all")
    parser.add_argument("--k", type=int, nargs="+", default=DEFAULT_KS, metavar="K",
                        help="cut-offs for precision@k (default: 100 500 1000)")
    args = parser.parse_args(argv)

    if not args.path.exists():
        print(f"No file at {args.path}. Download the IBM AML files from Kaggle; "
              "see docs/EVALUATION.md, \"External data\".")
        return 1
    if args.max_rows <= 0:
        parser.error("--max-rows must be positive")
    try:
        result = evaluate_external(args.path, args.max_rows, args.currency, args.k,
                                   start=args.start, end=args.end)
    except ValueError as exc:
        print(exc)
        return 1
    report(result)
    return 0


if __name__ == "__main__":
    sys.exit(main())
